import json
from unittest.mock import Mock

import pytest

from ci_doctor import match_night, parse_item, refresh
from github_api import GitHubApi, GitHubApiError

REPOSITORY = "openvinotoolkit/openvino_notebooks"
RUN_URL = f"https://github.com/{REPOSITORY}/actions/runs/123"
DISPLAY_RUN_URL = RUN_URL.replace("_", "\\_")
BODY = f"""## Error signature
Error signature: `abcdef123456`
Nightly run: [{DISPLAY_RUN_URL}]({RUN_URL})
Related signatures: `111111111111`

## Affected notebooks
| Notebook | Configs | Status | Previous night |
|---|---|---|---|
| `notebooks/demo/demo.ipynb` | `cpu-ubuntu-22.04-py3.12`, `cpu-windows-2022-py3.12` | failed | passed |

## History
`notebooks/unrelated/unrelated.ipynb` also failed previously.
Generated by https://github.com/{REPOSITORY}/actions/runs/999
<!-- gh-aw-workflow-id: nightly-issue-remediator -->
"""


def issue(number=10, **kwargs):
    return {"number": number, "title": "Nightly failure", "html_url": f"https://github.com/{REPOSITORY}/issues/{number}", "body": BODY, **kwargs}


def test_parse_explicit_references_not_related_signatures_or_agent_runs():
    parsed = parse_item(issue(), REPOSITORY)
    assert parsed["signature"] == "abcdef123456"
    assert parsed["run_id"] == "123"
    assert parsed["affected"] == [{"notebook": "demo/demo.ipynb", "configs": ["cpu-ubuntu-22.04-py3.12", "cpu-windows-2022-py3.12"]}]
    assert parsed["kind"] == "issue"
    assert parse_item(issue(pull_request={}), REPOSITORY)["kind"] == "pr"
    assert parse_item(issue(body="## History\nsig abcdef123456\n" + RUN_URL), REPOSITORY)["run_id"] is None


def test_refresh_filters_unrelated_issues_and_replaces_closed_items(tmp_path):
    path = tmp_path / "ci_doctor.json"
    path.write_text('{"items":[{"number":1}]}')
    api = Mock(spec=GitHubApi)
    api.search_issues.side_effect = [
        [issue(11, pull_request={})],
        [issue(), issue(12, body="Unrelated assigned issue"), issue(13, body="", labels=[{"name": "nightly-remediator"}])],
    ]
    snapshot = refresh(api, REPOSITORY, path, now="2026-11-25T08:00:00Z")
    assert [item["number"] for item in snapshot["items"]] == [13, 11, 10]
    assert snapshot["warnings"] == ["CI Doctor issue #13 has no explicit nightly run or error signature; it cannot be linked."]
    assert json.loads(path.read_text()) == snapshot
    queries = [call.args[0] for call in api.search_issues.call_args_list]
    assert "is:pr is:open label:automated-fix" in queries[0]
    assert "is:issue is:open assignee:akashchi" in queries[1]


def test_failed_refresh_leaves_previous_snapshot_untouched(tmp_path):
    path = tmp_path / "ci_doctor.json"
    path.write_text('{"items":[]}')
    api = Mock(spec=GitHubApi)
    api.search_issues.side_effect = [[], GitHubApiError("rate limited")]
    with pytest.raises(GitHubApiError, match="rate limited"):
        refresh(api, REPOSITORY, path)
    assert path.read_text() == '{"items":[]}'


def test_matching_requires_signature_and_declared_notebook_config_scope():
    def failure(notebook="demo/demo.ipynb", config="cpu-ubuntu-22.04-py3.12", signature="abcdef123456"):
        return {"notebook": notebook, "config_id": config, "signature": signature}

    night = {"run": {"id": 456}, "failures": {
        "match": failure(),
        "different-error": failure(signature="111111111111"),
        "different-notebook": failure(notebook="other/other.ipynb"),
        "different-config": failure(config="igpu-ubuntu-22.04-py3.11"),
    }}
    snapshot = {"updated_at": "2026-11-25T08:00:00Z", "items": [parse_item(issue(), REPOSITORY)]}
    result = match_night(night, snapshot)
    assert result["ci_doctor"]["items"][0]["failure_ids"] == ["match"]
    assert result["failures"]["match"]["ci_doctor"][0]["number"] == 10
    assert all(not result["failures"][key]["ci_doctor"] for key in ["different-error", "different-notebook", "different-config"])
    assert "ci_doctor" not in night["failures"]["match"]
    # A source run alone links the issue to the night, not to an unrelated failure.
    source_only = match_night({"run": {"id": 123}, "failures": {"other": failure(signature="other")}}, snapshot)
    assert source_only["ci_doctor"]["items"][0]["failure_ids"] == []
    assert not source_only["failures"]["other"]["ci_doctor"]


def test_unsigned_records_require_exact_source_run_and_scope():
    item = parse_item(issue(body=BODY.replace("Error signature: `abcdef123456`", "")), REPOSITORY)
    failure = {"notebook": "demo/demo.ipynb", "config_id": "cpu-ubuntu-22.04-py3.12"}
    snapshot = {"items": [item]}
    assert match_night({"run": {"id": 123}, "failures": {"f": failure}}, snapshot)["ci_doctor"]["items"][0]["failure_ids"] == ["f"]
    assert match_night({"run": {"id": 456}, "failures": {"f": failure}}, snapshot)["ci_doctor"]["items"] == []
    assert match_night({"run": None}, None)["ci_doctor"]["updated_at"] is None
